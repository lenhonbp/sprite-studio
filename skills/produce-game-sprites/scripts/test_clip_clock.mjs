import assert from 'node:assert/strict';
import {createClipClock,sampleClip} from '../assets/clip-clock.mjs';
import {validateResult} from './runtime_render.mjs';
const clip={name:'attack',loop:false,frames:[{id:'a',duration_ms:80},{id:'b',duration_ms:170},{id:'c',duration_ms:50}],events:[{name:'start',time_ms:0},{name:'hit',time_ms:80},{name:'end',time_ms:299}]};
const received=[];const clock=createClipClock(clip,e=>received.push(e));
clock.start();assert.equal(received.length,1);assert.equal(clock.advance(79).frame.id,'a');
assert.equal(clock.advance(1).frame.id,'b');assert.equal(received.at(-1).frameId,'b');
clock.pause();assert.equal(clock.advance(100).localTimeMs,80);clock.resume();
assert.equal(clock.advance(220).frame.id,'c');assert.equal(received.length,3);assert.equal(clock.state().playing,false);
clock.advance(1000);assert.equal(received.length,3);clock.start();assert.equal(received.length,4);
clock.stop();clock.advance(1000);assert.equal(received.length,4);
assert.equal(sampleClip(clip,80).index,1);assert.equal(sampleClip(clip,300).index,2);
const loop={...clip,name:'aura',loop:true};const loopEvents=[];const looping=createClipClock(loop,e=>loopEvents.push(e));
looping.start();looping.advance(600);assert.equal(looping.state().index,0);assert.equal(loopEvents.filter(e=>e.name==='hit').length,2);
assert.equal(loopEvents.filter(e=>e.name==='start').length,3);
assert.throws(()=>looping.advance(Infinity));assert.throws(()=>looping.advance(-1));assert.throws(()=>looping.advance(1e9));
let interrupted=[];let active;active=createClipClock(clip,e=>{interrupted.push(e);if(e.name==='hit')active.stop();});active.start();active.advance(300);
assert.deepEqual(interrupted.map(e=>e.name),['start','hit']);
// Stop/pause callbacks cancel remaining dispatch, including time zero.
const cancelled=[];let cancelling;
cancelling=createClipClock({...clip,events:[{name:'cancel',time_ms:0},{name:'unexpected',time_ms:0}]},e=>{cancelled.push(e.name);cancelling.stop();});
cancelling.start();assert.deepEqual(cancelled,['cancel']);
const pausedEvents=[];let pausing;
pausing=createClipClock({...clip,events:[{name:'pause',time_ms:10},{name:'later',time_ms:20}]},e=>{pausedEvents.push(e.name);if(e.name==='pause')pausing.pause();});
pausing.start();pausing.advance(100);assert.deepEqual(pausedEvents,['pause']);assert.equal(pausing.state().absoluteTimeMs,10);
pausing.resume();pausing.advance(10);assert.deepEqual(pausedEvents,['pause','later']);
assert.ok(validateResult({clips:[],cell_size:[16,16]},null).length);
const timeline={cell_size:[16,16],clips:[clip]};
assert.ok(validateResult(timeline,{frames:[],errors:[],version:'8.22.0'}).length);
const frames=clip.frames.map((f,index)=>({...f,clip:'attack',index,width:16,height:16,visiblePixels:10,differentPixels:0,png:'data:image/png;base64,x'}));
assert.deepEqual(validateResult(timeline,{frames,errors:[],version:'8.22.0'}),[]);
assert.ok(validateResult(timeline,{frames:frames.slice(1),errors:[],version:'8.22.0'}).length);
assert.ok(validateResult(timeline,{frames,errors:['engine failed'],version:'8.22.0'}).length);
assert.ok(validateResult(timeline,{frames:[...frames].reverse(),errors:[],version:'8.22.0'}).length);
assert.ok(validateResult(timeline,{frames:frames.map(f=>({...f,visiblePixels:0})),errors:[],version:'8.22.0'}).length);
assert.ok(validateResult(timeline,{frames,errors:[],version:null}).length);
console.log('Clip clock and render-result negative/coverage regressions passed (no engine rendering claimed)');
